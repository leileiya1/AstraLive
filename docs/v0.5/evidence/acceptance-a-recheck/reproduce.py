#!/usr/bin/env python3
"""Local owned PostgreSQL focused recheck; no real providers or cloud access.

Archives pinned production/test sources; never changes C/A production files.
Uses only synthetic credentials generated by the existing CPU tests.
"""
import argparse
import getpass
import hashlib
import json
import os
from pathlib import Path
import socket
import subprocess
import tarfile
import tempfile
import time

SOURCE = 'aab062f024fa28202a7255179c5089c1dc9bdbbd'
PG_BIN = Path('/opt/homebrew/opt/postgresql@17/bin')
PYTHON = '/private/tmp/astralive-f-media-venv-1/bin/python'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=False)
    tree = out / 'source'
    tree.mkdir()
    env = {key: os.environ[key] for key in ['PATH', 'HOME', 'TMPDIR', 'LANG'] if key in os.environ}
    archive = subprocess.Popen(['git', '-C', str(args.repo), 'archive', SOURCE, 'backend', 'runtime', 'gpu_worker', 'contracts'], stdout=subprocess.PIPE)
    with tarfile.open(fileobj=archive.stdout, mode='r|*') as handle:
        handle.extractall(tree, filter='data')
    if archive.wait():
        raise RuntimeError('source archive failed')
    report = {'source': SOURCE, 'scope': 'owned local PG, actual Go/CPU Runtime processes and controlled boundary/provider/sink fixtures; no real GPU/LLM/Chrome/RTMP or live crash claim', 'commands': []}
    data = Path(tempfile.mkdtemp(prefix='astralive-pg-chaos.', dir=out))
    owner = 'acceptance-a-20261015'
    started = False
    error = None

    def run(name, argv, cwd=None, process_env=None, timeout=180):
        began = time.monotonic()
        with (out / (name + '.log')).open('wb') as log:
            result = subprocess.run(argv, cwd=cwd, env=process_env or env, stdout=log, stderr=subprocess.STDOUT, timeout=timeout)
        report['commands'].append({'name': name, 'argv': argv, 'exitCode': result.returncode, 'elapsedSeconds': round(time.monotonic()-began, 3)})
        print(json.dumps(report['commands'][-1]), flush=True)
        if result.returncode:
            raise RuntimeError(name + ' failed')

    try:
        run('pg-init', [str(PG_BIN/'initdb'), '-D', str(data), '-A', 'trust', '--no-locale', '-E', 'UTF8'])
        (data/'.astralive-durability-owned').write_text(owner)
        with socket.socket() as listener:
            listener.bind(('127.0.0.1', 0))
            port = listener.getsockname()[1]
        with (data/'postgresql.conf').open('a') as handle:
            handle.write(f"\nport={port}\nlisten_addresses='127.0.0.1'\nunix_socket_directories=''\n")
        run('pg-start', [str(PG_BIN/'pg_ctl'), '-D', str(data), '-l', str(out/'postgres.log'), 'start'])
        started = True
        run('pg-createdb', [str(PG_BIN/'createdb'), '-h', '127.0.0.1', '-p', str(port), 'acceptance_a'])
        dsn = f'postgres://{getpass.getuser()}@127.0.0.1:{port}/acceptance_a?sslmode=disable'
        test_env = dict(env, DURABILITY_TEST_DATABASE_URL=dsn, CONFIG_TEST_DATABASE_URL=dsn,
                        DURABILITY_TEST_PYTHON=PYTHON, NARRATION_TEST_PYTHON=PYTHON,
                        PYTHONPATH=str(tree/'runtime')+os.pathsep+str(tree),
                        DURABILITY_OWNED_PGDATA=str(data), DURABILITY_PG_CTL=str(PG_BIN/'pg_ctl'), DURABILITY_PG_OWNER=owner)
        focus = ['PostgresJournalIdempotencyAndFences', 'TwoDispatchersLeaseExpiryOldAck', 'RecoveryStopRaceAndOldEpoch',
                 'EventDupConflictReorderAndTerminal', 'AcceptedBeforeLostACK', 'UnknownProbeBudgetAndNoReplay',
                 'ControlReceipt', 'ForceFencesDelayedSpeakAndStopExpiredRun', 'StopConcurrentWithRecovery',
                 'MediaAttemptGenerationAndEventFence', 'PreparingStopUnknownStartupReleasedBinding',
                 'PreparingStopForceRaceRetainsCleanupOnly', 'TerminalSessionSealsContinuity']
        run('durability-race', ['go', 'test', '-race', '-count=1', '-timeout=120s', '-v', './internal/durability', '-run', '^Test('+'|'.join(focus)+')$'], tree/'backend', test_env)
        run('redis-off-process-race', ['go', 'test', '-race', '-count=1', '-timeout=120s', '-v', './internal/durability', '-run', '^Test(PostgresOnlyServerStartup|RuntimeProcessCrashRedisOff)$'], tree/'backend', test_env)
        run('bridge-stop-proof-race', ['go', 'test', '-race', '-count=1', '-timeout=120s', '-v', './internal/narration', '-run', '^Test(PostgresNewResumeBridgeEmptyFactsCanonical|PostgresPrephysicalFailedCreateStopProof)$'], tree/'backend', test_env)
        run('public-auth-race', ['go', 'test', '-race', '-count=1', '-timeout=120s', '-v', './internal/httpapi', '-run', '^TestProductAuthorizationAndPinnedBindings$'], tree/'backend', test_env)
        # Never overlap the owned-PG outage with any other process/test command.
        run('owned-pg-outage-race', ['go', 'test', '-race', '-count=1', '-timeout=120s', '-v', './internal/durability', '-run', '^TestOwnedPostgresOutage$'], tree/'backend', test_env)
    except Exception as exc:
        error = type(exc).__name__ + ': ' + str(exc)
    finally:
        if started:
            try:
                run('pg-stop', [str(PG_BIN/'pg_ctl'), '-D', str(data), '-m', 'fast', 'stop'])
            except Exception as exc:
                error = (error or '') + ' cleanup: ' + str(exc)
        report['status'] = 'FAIL' if error else 'PASS'
        report['error'] = error
        report['scriptSHA256'] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        report['files'] = {str(path.relative_to(tree)): hashlib.sha256(path.read_bytes()).hexdigest()
                           for path in sorted(tree.rglob('*')) if path.is_file() and path.suffix in ('.go', '.py', '.sql')}
        report['artifacts'] = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
                               for path in out.iterdir() if path.is_file() and path.name != 'result.json'}
        (out/'result.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps({'source': SOURCE, 'status': report['status'], 'error': error}), flush=True)
    return int(error is not None)


if __name__ == '__main__':
    raise SystemExit(main())
