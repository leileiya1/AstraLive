"""Generate Go DTOs and frozen local schema closure. No schema invention."""
import hashlib,json,pathlib
root=pathlib.Path(__file__).resolve().parents[2]
src=root/'contracts/v0.5/durable-live'
out=root/'backend/internal/durablelive'
schema=json.loads((src/'schema.json').read_text())
def name(v): return v[0].upper()+v[1:]
def typ(v):
 if '$ref' in v: return v['$ref'].split('/')[-1]
 if 'anyOf' in v:
  non=[x for x in v['anyOf'] if x.get('type')!='null']
  return '*'+typ(non[0]) if len(non)==1 else 'json.RawMessage'
 t=v.get('type')
 if t=='array': return '[]'+typ(v['items'])
 if t=='integer': return 'int64'
 if t=='boolean' or isinstance(v.get('const'),bool): return 'bool'
 if t=='string' or 'const' in v: return 'string'
 return 'json.RawMessage'
lines=['// Code generated by scripts/durable-live/generate_contract.py; DO NOT EDIT.','package durablelive','import ("context"; "encoding/json")']
for k,v in schema['$defs'].items():
 if v.get('type')=='object':
  lines.append('type '+k+' struct {')
  for field,sp in v['properties'].items(): lines.append(name(field)+' '+typ(sp)+' `json:"'+field+'"`')
  lines.append('}')
 else: lines.append('type '+k+' = '+typ(v))
p=json.loads((src/'protocol.json').read_text())
for op in p['operations']:
 if op['target']!='BACKEND': continue
 n=op['operationId'];req=op['requestSchema'].split('/')[-1];resp=op['responseSchema'].split('/')[-1]
 lines.append(f'func (s *Store) {n}(ctx context.Context, p Principal, req {req}) (out {resp}, err error) {{ b,err:=json.Marshal(req); if err!=nil {{return}}; r,err:=s.Call(ctx,p,"{n}",b); if err!=nil {{return}}; b,err=json.Marshal(r); if err==nil {{err=json.Unmarshal(b,&out)}}; return }}')
(out/'contract_generated.go').write_text('\n'.join(lines)+'\n')
for f in ['schema.json','protocol.json','state-machines.json']:
 (out/'spec'/f).write_bytes((src/f).read_bytes())
print('contract SHA256',hashlib.sha256((src/'schema.json').read_bytes()).hexdigest())
