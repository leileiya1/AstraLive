"""Generate wire shapes ONLY from the frozen schema. Run from any directory."""
import hashlib
import json
from pathlib import Path
import subprocess
root = Path(__file__).resolve().parents[4]
source = root / 'contracts/v0.5/durable-live/schema.json'
schema = json.loads(source.read_text())
def name(s):
    # Preserve schema spelling mechanically; no independently designed DTOs.
    return s[0].upper() + s[1:]
def typ(s):
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'anyOf' in s:
        nonnull = [x for x in s['anyOf'] if x.get('type') != 'null']
        return '*' + typ(nonnull[0])
    t = s.get('type')
    if t == 'array': return '[]' + typ(s['items'])
    if t == 'integer': return 'int64'
    if t == 'boolean' or isinstance(s.get('const'), bool): return 'bool'
    if t == 'object': return 'map[string]json.RawMessage'
    if t == 'null': return '*json.RawMessage'
    if t == 'string' or isinstance(s.get('const'), str): return 'string'
    raise ValueError(s)
lines = ['// Code generated by generate.py from durable-live-1 schema; DO NOT EDIT.',
         '// Schema SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
         'package contract', 'import "encoding/json"', 'var _ json.RawMessage',
         'const RevisionName = "durable-live-1"', 'const SchemaVersion = "0.5"',
         'const IDPattern = '+json.dumps(schema['$defs']['ID']['pattern']),
         'const HashPattern = '+json.dumps(schema['$defs']['Hash']['pattern']),
         'const TimestampPattern = '+json.dumps(schema['$defs']['Timestamp']['pattern']),
         'const MaxInteger int64 = '+str(schema['$defs']['Epoch']['maximum'])]
for k, s in schema['$defs'].items():
    if s.get('type') == 'object':
        lines += ['type '+k+' struct {']
        for p, v in s['properties'].items(): lines += [name(p)+' '+typ(v)+' `json:"'+p+'"`']
        lines += ['}']
    else: lines += ['type '+k+' = '+typ(s)]
path = Path(__file__).with_name('types.gen.go')
path.write_text('\n'.join(lines)+'\n')
subprocess.run(['gofmt', '-w', str(path)], check=True)

# Full example wire-shape round trips catch dropped fields/nullability drift.
protocol = json.loads((root / 'contracts/v0.5/durable-live/protocol.json').read_text())
t = ['// Code generated by generate.py; DO NOT EDIT.', 'package contract_test',
 'import ("encoding/json"; "os"; "reflect"; "testing"; c "astralive/backend/internal/contentplan/contract")',
 'func TestProtocolExampleRoundTrips(t *testing.T){',
 'b,e:=os.ReadFile("../../../../contracts/v0.5/durable-live/examples/protocol.json");if e!=nil{t.Fatal(e)}',
 'var rows []struct{OperationId string;Request,Response json.RawMessage};if e=json.Unmarshal(b,&rows);e!=nil{t.Fatal(e)}',
 'for _,r:=range rows{t.Run(r.OperationId,func(t *testing.T){var req,res any;switch r.OperationId {']
for op in protocol['operations']:
    a,b = [op[k].split('/')[-1] for k in ('requestSchema','responseSchema')]
    t += ['case "'+op['operationId']+'": req=&c.'+a+'{};res=&c.'+b+'{}']
t += ['default:t.Fatal("unhandled operation")}',
 'for i,raw:=range []json.RawMessage{r.Request,r.Response}{value:=req;if i==1{value=res};if e:=json.Unmarshal(raw,value);e!=nil{t.Fatal(e)};encoded,e:=json.Marshal(value);if e!=nil{t.Fatal(e)};var before,after any;json.Unmarshal(raw,&before);json.Unmarshal(encoded,&after);if !reflect.DeepEqual(before,after){t.Fatalf("wire shape drift: %s",encoded)}}', '})}}']
testpath = Path(__file__).with_name('roundtrip.gen_test.go')
testpath.write_text('\n'.join(t)+'\n')
subprocess.run(['gofmt','-w',str(testpath)],check=True)
